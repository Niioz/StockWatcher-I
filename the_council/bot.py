@bot.command(name='reflect')
async def reflect(ctx, period: str = None):
    """Review past predictions and generate a reflection report.
    Usage: !reflect [weekly|monthly|quarterly]
    """
    period = period.lower() if period else None
    valid_periods = ("weekly", "monthly", "quarterly")
    if period and period not in valid_periods:
        await ctx.send(f"❌ Unknown period '{period}'. Use: weekly, monthly, quarterly, or no argument for full history.")
        return

    label = "full history" if not period else period
    await ctx.send(f"📜 Calling The Historian. Reviewing {label} to improve our strategies...\n*(Please wait...)*")
    try:
        from crew_setup import create_crew_for_reflect
        result = await asyncio.to_thread(create_crew_for_reflect, period)
        await _send_report(ctx, str(result))
    except Exception as e:
        await ctx.send(f"❌ The team encountered an error: {e}")


@bot.command(name='filings')
async def filings(ctx, ticker: str):
    """Fetch latest SEC filings (10-K, 10-Q, 8-K) for a ticker and save to stocks.md.
    Usage: !filings MSFT
    """
    await ctx.send(f"📄 Fetching SEC filings for **{ticker.upper()}**...")
    try:
        from tools import fetch_sec_filings
        result = await asyncio.to_thread(fetch_sec_filings.run, ticker)

        if result.startswith("Error") or result.startswith("No "):
            await ctx.send(f"❌ {result}")
            return

        _update_stocks_md(ticker, result)
        await ctx.send(f"✅ SEC filings for **{ticker.upper()}** saved to `stocks.md`. Latest entries:")
        await _send_report(ctx, result)
    except Exception as e:
        await ctx.send(f"❌ Could not fetch filings: {e}")


