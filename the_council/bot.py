_STOCKS_FILE = os.path.join(os.path.dirname(__file__), "stocks.md")


async def _send_report(ctx, report: str):
    max_len = 1980
    if len(report) <= max_len:
        await ctx.send(report)
        return
    parts = [report[i:i+max_len] for i in range(0, len(report), max_len)]
    for i, part in enumerate(parts):
        msg = f"*(Part {i+1}/{len(parts)})*\n{part}" if i > 0 else part
        await ctx.send(msg)


def _update_stocks_md(ticker: str, filings_data: str):
    """Append or update SEC filings data in stocks.md."""
    os.makedirs(os.path.dirname(_STOCKS_FILE) or ".", exist_ok=True)
    date_str = datetime.now().strftime("%Y-%m-%d")

    # Build the new entry block
    new_block = f"\n## {ticker.upper()}\n"
    new_block += f"### Last Updated: {date_str}\n\n"
    new_block += "| Form | Filed | Period End | Description | Link |\n"
    new_block += "|------|-------|-----------|-------------|------|\n"

    for line in filings_data.strip().split("\n"):
        line = line.strip()
        if line.startswith("Form:"):
            form = line.split("Form:")[1].strip()
        elif line.startswith("Filed:"):
            filed = line.split("Filed:")[1].strip()
        elif line.startswith("Period End:"):
            period = line.split("Period End:")[1].strip()
        elif line.startswith("Description:"):
            desc = line.split("Description:")[1].strip()[:50]
        elif line.startswith("Link:"):
            link = line.split("Link:")[1].strip()
            new_block += f"| {form} | {filed} | {period} | {desc} | [view]({link}) |\n"

    new_block += "\n"

    if not os.path.exists(_STOCKS_FILE):
        with open(_STOCKS_FILE, "w", encoding="utf-8") as f:
            f.write("# The Council — SEC Filings Database\n")
            f.write(f"Auto-generated by !filings command\n\n")
            f.write(new_block)
        return

    with open(_STOCKS_FILE, "r", encoding="utf-8") as f:
        content = f.read()

    # If ticker section exists, replace it
    header = f"## {ticker.upper()}\n"
    ticker_start = content.find(header)
    if ticker_start != -1:
        next_section = content.find("\n## ", ticker_start + 1)
        if next_section == -1:
            content = content[:ticker_start] + new_block
        else:
            content = content[:ticker_start] + new_block + content[next_section:]
    else:
        content += new_block

    with open(_STOCKS_FILE, "w", encoding="utf-8") as f:
        f.write(content)


